dotenv.config({ path: path.resolve(__dirname, '../../.env') });

function requireEnv(name) {
  const value = process.env[name];
  if (!value) throw new Error(`Missing required environment variable: ${name}`);
  return value;
}

function parseAllowedOrigins() {
  const raw = [process.env.CORS_ORIGIN, process.env.FRONTEND_URL, 'http://localhost:5173']
    .filter(Boolean)
    .join(',');
  return [...new Set(raw.split(',').map((o) => o.trim().replace(/\/$/, '')).filter(Boolean))];
}

// Supports exact origins and wildcards such as "https://*.vercel.app"
function makeOriginMatcher(origins) {
  const patterns = origins.map((o) =>
    o.includes('*')
      ? new RegExp(`^${o.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '[a-z0-9-]+')}$`, 'i')
      : o
  );
  return (origin) => {
    if (!origin) return true; // same-origin, curl, server-to-server
    return patterns.some((p) => (typeof p === 'string' ? p === origin : p.test(origin)));
  };
}

function getFrontendUrl() {
  const value = process.env.FRONTEND_URL || 'http://localhost:5173';
  return value.replace(/\/$/, '');
}

// Percent-encode the username/password in a MongoDB URI if they contain characters
// such as # $ / ? @ : that the driver rejects (common with autogenerated passwords).
function normaliseMongoUri(uri) {
  const m = /^(mongodb(?:\+srv)?:\/\/)(.*)$/.exec(String(uri).trim());
  if (!m) return uri;
  const [, scheme, rest] = m;
  const at = rest.lastIndexOf('@');
  if (at === -1) return uri;
  const creds = rest.slice(0, at);
  const hostPart = rest.slice(at + 1);
  const colon = creds.indexOf(':');
  const fix = (part) => {
    try {
      const decoded = decodeURIComponent(part);
      return encodeURIComponent(decoded) === part ? part : encodeURIComponent(decoded);
    } catch {
      return encodeURIComponent(part);
    }
  };
  const user = colon === -1 ? creds : creds.slice(0, colon);
  const pass = colon === -1 ? null : creds.slice(colon + 1);
  return `${scheme}${fix(user)}${pass === null ? '' : `:${fix(pass)}`}@${hostPart}`;
}

const rawMongoUri = process.env.MONGO_URI || process.env.MONGODB_URI;
if (!rawMongoUri) throw new Error('Missing required environment variable: MONGO_URI');
const mongoUri = normaliseMongoUri(rawMongoUri);

const jwtSecret = requireEnv('JWT_SECRET');
if ((process.env.NODE_ENV === 'production') && (jwtSecret.length < 32 || /change|your|secret-key/i.test(jwtSecret))) {
  throw new Error('JWT_SECRET is too weak for production — set a random value of at least 32 characters');
}
const allowedOrigins = parseAllowedOrigins();

const env = {
  nodeEnv:          process.env.NODE_ENV || 'development',
  port:             Number(process.env.PORT || 5000),
  mongoUri,
  jwtSecret,
  jwtExpiresIn:     process.env.JWT_EXPIRES_IN || '7d',
  frontendUrl:      getFrontendUrl(),
  allowedOrigins,
  isAllowedOrigin:  makeOriginMatcher(allowedOrigins),
  emailHost:        process.env.EMAIL_HOST || '',
  emailPort:        Number(process.env.EMAIL_PORT || 587),
  emailUser:        process.env.EMAIL_USER || '',
  emailPassword:    process.env.EMAIL_PASSWORD || '',
  emailFromName:    process.env.EMAIL_FROM_NAME || 'Boarding Book',
  emailFromAddress: process.env.EMAIL_FROM_ADDRESS || process.env.EMAIL_USER || '',
};


env.normaliseMongoUri = normaliseMongoUri;
module.exports = env;